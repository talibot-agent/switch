"""Live demo: Switch IRC adapter against a real IRC server (miniircd on localhost).
A human IRC user 'mykel' and the Switch bridge nick 'switch-bot' talk in #ops.
Generated by Tali (AI agent)."""
import asyncio, json, subprocess, sys, time
from switch_core.bridges.collaboration.irc.adapter import IrcAdapter, IrcConnectionConfig
from switch_core.bridges.collaboration.platforms import PLATFORMS

def say(who, msg): print(f"[{time.strftime('%H:%M:%S')}] {who:<12} {msg}", flush=True)

async def human():
    r, w = await asyncio.open_connection("127.0.0.1", 6667)
    for l in ["NICK mykel", "USER mykel 0 * :Mykel", "JOIN #ops"]:
        w.write((l + "\r\n").encode())
    await w.drain()
    async def reader(q):
        while line := await r.readline():
            s = line.decode(errors="replace").strip()
            if s.startswith("PING"):
                w.write(s.replace("PING", "PONG", 1).encode() + b"\r\n"); await w.drain()
            elif " PRIVMSG #ops " in s:
                txt = s.split(" PRIVMSG #ops :", 1)[1].replace("\x02", "")
                say("IRC <- ", f"<switch-bot> {txt}"); await q.put(txt)
    q = asyncio.Queue(); asyncio.create_task(reader(q))
    async def send(t):
        say("IRC -> ", f"<mykel> {t}"); w.write(f"PRIVMSG #ops :{t}\r\n".encode()); await w.drain()
    return send, q

async def main():
    say("SWITCH", "== Step 1: IRC connect form (fields Switch renders for the platform) ==")
    entry = next(p for p in PLATFORMS if p.key == "irc")
    schema = IrcConnectionConfig.model_json_schema()
    for k, v in schema["properties"].items():
        say("  form", f"{k:<16} {v.get('title','')} default={v.get('default','—')}")
    form = {"server": "localhost", "port": 6667, "tls": False, "nickname": "switch-bot", "channels": "#ops"}
    say("SWITCH", f"submitted form: {json.dumps(form)}")
    await IrcAdapter.verify_credentials(form)
    say("SWITCH", "verify_credentials: OK (real TCP connect + IRC registration)")
    send, q = await human(); await asyncio.sleep(0.5)
    got = asyncio.Queue()
    async def on_message(m): say("SWITCH <- ", f"InboundMessage from {m.sender_name} in {m.channel_name}: {m.content!r}"); await got.put(m)
    async def on_command(c): say("SWITCH <- ", f"InboundCommand !{c.command} args={c.args!r} from {c.sender_name}"); await got.put(c)
    async def nop(*_): pass
    ad = IrcAdapter(config=IrcConnectionConfig.model_validate(form))
    await ad.start(on_message, on_command, nop, nop, nop)
    await asyncio.sleep(1.5)
    say("SWITCH", "== Step 2: two-way messages ==")
    await send("claude: can you check the deploy status?")
    m = await asyncio.wait_for(got.get(), 10)
    await ad.send_message(m.channel_id, "claude", "Deploy #482 is green on staging. Production rollout is waiting on approval.")
    await asyncio.wait_for(q.get(), 10)
    say("SWITCH", "== Step 3: approval card from IRC (no buttons on IRC, so the card is text, answered by typing) ==")
    card = ("APPROVAL REQUEST #1 | claude wants to run: kubectl rollout restart deploy/api -n prod | "
            "Reply !approve 1 or !deny 1")
    await ad.send_message(m.channel_id, "claude", card)
    await asyncio.wait_for(q.get(), 10)
    await send("!approve 1")
    c = await asyncio.wait_for(got.get(), 10)
    assert c.command == "approve" and c.args == "1"
    await ad.send_message(c.channel_id, "claude", f"Approved by {c.sender_name}. Running rollout now.")
    await asyncio.wait_for(q.get(), 10)
    await ad.stop(); say("SWITCH", "demo complete: connect form, two-way chat, approval round-trip all over real IRC")

asyncio.run(main())
